-- 주인(관리자 비밀번호로 들어온 기기)의 방문자 id 를 적어 둔다.
--
-- 왜 이 표가 필요한가: 이 아카이브는 만든 사람이 자기가 만든 화면을 가장 자주
-- 연다. 관리자 화면에서 확인 삼아 도메인 앱을 열어 보는 것, 새 기능을 배포하고
-- 눈으로 확인하는 것 — 이런 방문이 숫자의 대부분을 차지하면 통계는 "실제로
-- 얼마나 쓰이는가"가 아니라 "본인이 언제 접속했는가"의 기록이 되어 버린다.
-- 그러면 이 워커가 풀려는 문제(design §1) 자체가 무의미해진다.
--
-- 그래서 관리자 비밀번호(METRICS_TOKEN)로 들어온 기기의 방문자 id 를 여기
-- 적어 두고, stats.mjs 의 모든 집계 질의가 이 표에 있는 방문자를 뺀다.
CREATE TABLE owner (
  visitor TEXT PRIMARY KEY,
  added   TEXT NOT NULL   -- 등록한 날(KST). 감사용 — 집계에는 안 쓰인다
);
