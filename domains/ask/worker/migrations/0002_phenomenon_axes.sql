-- 현상이 **자기가 어느 집단축의 이야기인지** 스스로 선언하게 한다.
--
-- 없을 때 무슨 일이 일어났나: 현상찾기가 이름·정의 문자열에 주제 단어가 들어 있는지
-- 만 봤다. 등록 현상이 "15~29세 사무 종사자 취업자수 감소" 하나뿐인데 정의에
-- "취업자수" 가 들어 있어 **취업자를 묻는 모든 원인탐색 질문이 여기로 걸렸다** —
-- "제조업이 왜 줄었냐" 에 "청년 사무직이 줄었다" 를 답했다(2026-09-09 화면 실측).
--
-- JSON 객체다: {"연령":"15-29","직업":"3"}. 값 체계는 classify.mjs 의 카테고리_SYN
-- 코드계와 같다(연령은 observation.category, 직업은 KSCO 대분류 한 자리).
-- 선언하지 않은 축은 **판정에 쓰지 않는다** — 성을 안 적은 현상에 성을 물었다고
-- 거부하면 지나치게 좁아진다.
ALTER TABLE phenomenon ADD COLUMN 집단축 TEXT;

UPDATE phenomenon SET 집단축 = '{"연령":"15-29","직업":"3"}'
 WHERE id = '청년사무직감소';
