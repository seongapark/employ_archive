-- 초록·목차·전망근거·카탈로그 설명을 **한 색인**에 담는다. 도메인은 열로 가른다.
--
-- 왜 한 표인가: 도메인마다 표를 쪼개면 질문 하나에 네 번 조회하고 순위를 손으로
-- 합쳐야 한다. `도메인` 열 하나면 한 번 조회하고 나누기만 하면 된다.
--
-- ── 토크나이저를 trigram 으로 두고 **공백을 지운 사본을 색인한다** ──────────
--
-- 2026-09-10 에 실물 D1 에서 재 본 것(로컬 miniflare 가 아니라 원격이다):
--
--   · trigram 은 D1 에 있다. 붙는다.
--   · 낱말 중간도 걸린다 — `저임금 인` 이 "최저임금 인상" 에 걸렸다.
--   · **공백까지 그대로 맞아야 한다** — 본문이 "청년고용" 이면 `청년 고용` 이 안 걸린다.
--   · **세 글자 미만은 아예 안 걸린다** — `고용`·`임금` 이 0건이었다.
--
-- 앞의 것은 **양쪽에서 공백을 지워** 없앤다. 색인용 열(`제목색인`·`본문색인`)에는
-- 공백을 지운 사본을 넣고, 조회할 때 질의도 같은 규칙으로 지운다. 웹앱 검색이
-- `squash()` 로 푸는 그 문제이고 같은 해법이다("청년고용"과 "청년 고용"을 하나로).
--
-- 뒤의 것(두 글자)은 색인으로는 못 푼다. 워커가 **세 글자 미만이면 LIKE 로 훑는다** —
-- 지금 담는 본문이 2MB 남짓이라 전수 훑기가 감당된다. 데이터가 열 배가 되면 다시 잰다.
--
-- 원문(`제목`·`본문`)은 UNINDEXED 로 함께 둔다. 화면에 보여줄 스니펫은 공백이 살아
-- 있어야 읽히므로, 검색은 색인 열로 하고 표시는 원문 열로 한다.
DROP TABLE IF EXISTS doc_fts;

CREATE VIRTUAL TABLE doc_fts USING fts5(
  doc_id UNINDEXED,
  도메인 UNINDEXED,
  종류   UNINDEXED,
  링크   UNINDEXED,
  제목   UNINDEXED,
  본문   UNINDEXED,
  제목색인,
  본문색인,
  tokenize = 'trigram'
);
