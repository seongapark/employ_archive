// 출처 탐색 결과를 **요약 문장의 재료**로 접고, 그 재료에서 검증 집합을 뽑는다.
//
// 왜 한 함수가 둘을 같이 내는가: `verify` 의 허용 집합은 **우리가 실제로 LLM 에게
// 넘긴 것**이어야 한다. 재료를 만드는 자리와 허용 집합을 만드는 자리가 갈라지면 한쪽만
// 늘어나 조용히 어긋난다 — 넘겼는데 허용하지 않으면 정상 문장이 버려지고(실측: 전망
// 수치를 안 넘겨 답변이 늘 버려졌다), 안 넘겼는데 허용하면 환각 방어에 구멍이 뚫린다.
// 그래서 **재료를 한 번 걸어** 문자열과 숫자를 그대로 모은다.

// 재료에서 문자열과 숫자를 전부 모은다. 재료의 모양이 바뀌어도 따라온다.
function 걷기(v, 글, 수) {
  if (typeof v === 'string') { if (v) 글.push(v); return; }
  if (typeof v === 'number') { if (Number.isFinite(v)) 수.push(v); return; }
  if (Array.isArray(v)) { for (const x of v) 걷기(x, 글, 수); return; }
  if (v && typeof v === 'object') { for (const x of Object.values(v)) 걷기(x, 글, 수); }
}

export function 요약재료(응답) {
  const 도메인 = (응답?.묶음 ?? []).map((g) => ({
    도메인: g.도메인,
    ...(g.사유 ? { 사유: g.사유 } : {}),
    // **점수는 넘기지 않는다.** 우리 내부 순위값이라 문장에 인용될 값이 아니고,
    // 넘기면 허용 숫자 집합에 뜻 없는 수가 섞여 환각 방어가 그만큼 헐거워진다.
    출처: (g.결과 ?? []).map((x) => ({
      제목: x.제목 ?? '',
      ...(x.날짜 ? { 날짜: x.날짜 } : {}),
      종류: x.근거유형 ?? '',
      내용: x.스니펫 ?? '',
      // 질문의 말이 아니라 비슷한 말로 찾은 출처다. 밝히지 않으면 요약이 질문에 딱
      // 맞는 자료를 찾은 것처럼 말한다.
      ...(x.비슷한말 ? { 비슷한말: true } : {}),
    })),
    // 고용동향만 가진 것. 숫자가 사는 유일한 자리다.
    ...(g.관측?.length ? {
      관측: g.관측.map((o) => ({
        기간: o.period, 값: o.value, 단위: o.unit ?? '',
        ...(o.yoy != null ? { 전년대비: o.yoy } : {}),
      })),
    } : {}),
    ...(g.파생 && Object.keys(g.파생).length ? { 파생: g.파생 } : {}),
  }));

  const 재료 = {
    질문: 응답?.질문 ?? '',
    // 슬롯을 함께 넘긴다 — "일자리 사정" 을 취업자수로 읽었다는 사실을 문장이 밝힐 수 있다.
    이해한것: 응답?.슬롯 ?? {},
    도메인,
    해당없음: 응답?.해당없음 ?? [],
  };

  const 허용텍스트 = [];
  const 허용숫자 = [];
  걷기(재료, 허용텍스트, 허용숫자);
  return { 재료, 허용텍스트, 허용숫자 };
}
