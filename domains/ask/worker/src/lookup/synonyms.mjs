const squash = (s) => String(s ?? '').replace(/\s+/g, '');

// 한 질문에 붙일 확장어 상한. 두 글자 확장어는 LIKE 전수 훑기를 타므로 무한정 늘리면
// 조회가 무거워진다. 무리 둘이 걸리는 질문("청년 정년")까지는 이 상한 안에 들어온다.
const 상한 = 8;

// 용어와 무리 원소가 만나는지 본다. 한쪽이 다른 쪽을 품으면 만난 것으로 센다 —
// '청년고용률' 은 '청년고용' 을, '고용' 은 '고용상황' 을 품는다. 두 글자 미만은 보지
// 않는다(한 글자로 맞히면 아무 글에나 걸린다).
const 만난다 = (a, b) => a.length >= 2 && b.length >= 2 && (a.includes(b) || b.includes(a));

// 무리 하나가 질문과 얼마나 세게 만나는가. **그대로 같은 말이 가장 세다.**
//
// 품는 관계를 같은 자격으로 보면 엉뚱한 무리가 이긴다 — '계속고용' 은 '고용' 을 품으므로
// 고용 무리에 걸리는데, 정작 '계속고용' 이 **그대로 적혀 있는** 정년 무리가 상한에 밀려
// 잘려 나갔다(그래서 "계속고용" 을 물으면 '정년' 이 확장어에 없었다). 그대로 같은 말이
// 있으면 그 무리를 먼저 쓰고, 품는 관계는 그다음이다.
function 세기(무리하나, 원어) {
  let best = 0;
  for (const m of 무리하나) {
    const w = squash(m);
    for (const t of 원어) {
      if (t === w) best = Math.max(best, 100 + w.length);       // 그대로 같다
      else if (만난다(t, w)) best = Math.max(best, w.length);   // 한쪽이 품는다
    }
  }
  return best;
}

export function 확장(용어들) {
  const 원어 = (용어들 ?? []).map(squash).filter(Boolean);
  if (!원어.length) return [];

  // 만난 무리를 센 값 내림차순으로 쓴다 — 상한에 잘릴 때 덜 정확한 무리가 잘린다.
  const 걸린무리 = 무리
    .map((g) => ({ g, 점 : 세기(g, 원어) }))
    .filter((x) => x.점 > 0)
    .sort((a, b) => b.점 - a.점);

  const out = [];
  for (const { g } of 걸린무리) {
    for (const m of g) {
      const w = squash(m);
      // 원어에 이미 있는 말은 넣지 않는다 — 같은 조회를 두 번 돌리는 셈이다.
      if (원어.includes(w)) continue;
      if (!out.includes(w)) out.push(w);
    }
  }
  return out.slice(0, 상한);
}
