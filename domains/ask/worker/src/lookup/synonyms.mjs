// 낱말 무리. **같은 무리에 속한 말은 서로를 찾는다.**
//
// 왜 필요한가: 색인은 trigram 이라 글자가 그대로 맞아야 걸린다. "정년 연장" 을 물으면
// 본문에 '계속고용' 이라고 쓴 보고서가 한 건도 안 걸리고, "고용상황" 을 물으면 제목에
// '취업자' 라고 쓴 기사가 안 걸린다. 같은 것을 가리키는 말인데 글자가 달라서 못 만난다.
//
// **LLM 으로 풀지 않는다.** 정책 낱말은 몇십 개뿐이고 잘 안 바뀐다 — 표로 적는 쪽이
// 싸고 결정적이며, 질문마다 호출이 붙지 않는다. 같은 이유로 `주제_SYN`·`카테고리_SYN`
// 도 손으로 적힌 표다.
//
// **확장은 보충이지 대체가 아니다.** 확장어로 걸린 글은 `search.mjs` 에서 점수 0 을 받아
// 원어로 걸린 글 뒤에 선다. 그래서 원어만으로 충분한 질문의 순위는 한 자리도 안 바뀐다 —
// '고용' 처럼 거의 모든 글에 있는 말을 확장어로 넣어도 상위를 밀어내지 않는다.
