// 렌더 순수 함수. DOM 을 만지지 않는다 — 그래서 node --test 로 그냥 돈다.
//
// 배지는 전부 데이터(카드.배지 배열)에서 나온다. 화면이 배지를 지어내지 않는다.
// 8종(Task 12 에서 `할당량확인불가` 가 추가돼 7종에서 늘었다):
//   저확신 · 검증실패 · 한도초과 · 할당량확인불가 · 반증미설계 · 데이터미보유 ·
//   근거 미확인 · 유의성: 불명
//
// `한도초과` 와 `할당량확인불가` 는 겉보기엔 비슷해 보이지만 사용자가 할 수 있는
// 일이 다르다 — 한도초과는 "내일 다시"(사용자 몫을 다 씀), 할당량확인불가는
// "잠시 후 다시"(우리 KV 장애로 확인 자체를 못 함). 그래서 라벨을 다르게 낸다.
//
// `반증미설계` 와 `데이터미보유` 도 같은 이유로 라벨이 다르다 — 앞은 카탈로그에
// 반증 지표 자체가 설계돼 있지 않은 것(우리가 카탈로그를 늘려야 함), 뒤는 지표는
// 설계돼 있으나 관측이 아직 안 쌓인 것(수집기를 추가하면 풀림 — 승인 불요).
const BADGES = {
  저확신: { 라벨: '질문을 이렇게 이해했습니다 · 확인 필요', 색: 'warn' },
  검증실패: { 라벨: '답변 문장 검증 실패 · 근거만 표시', 색: 'warn' },
  한도초과: { 라벨: '오늘 문장 생성 한도 초과 · 내일 다시(근거는 표시)', 색: 'muted' },
  할당량확인불가: { 라벨: '이용량 확인 실패 · 잠시 후 다시(근거는 표시)', 색: 'muted' },
  반증미설계: { 라벨: '판정 불가 · 반증 지표가 카탈로그에 설계돼 있지 않음', 색: 'warn' },
  데이터미보유: { 라벨: '판정 불가 · 반증 지표 관측 미보유(수집기 추가로 해결)', 색: 'warn' },
  '근거 미확인': { 라벨: '일부 출처는 아직 확인하지 못함', 색: 'muted' },
  '유의성: 불명': { 라벨: '유의성 불명 · 표본오차 안인지 알 수 없음', 색: 'muted' },
};

// 모르는 코드가 와도 죽지 않는다 — 나중에 배지가 또 늘 수 있으므로, 코드 자체를
// 라벨로 쓰는 폴백을 둔다. 화면이 배지를 삼키는 것보다 낯선 문자열을 그대로
// 보여주는 쪽이 "왜 못 주는지" 를 안 숨긴다는 이 도구의 원칙에 맞는다.
export function badgeLabel(code) {
  return BADGES[code] ?? { 라벨: String(code), 색: 'muted' };
}

export function understandLine(유형) {
  return `${유형}으로 이해함 · 수정`;
}

// 지지 증거와 반증 증거를 좌우 두 열로 가른다 — 위아래로 쌓지 않는다. 이 병치
// 자체가 이 프로젝트의 주장이다(H1 을 주장하려면 H2 를 먼저 기각해야 한다).
// 반증 열이 비면 숨기지 않고 "비었다" 는 사실을 그린다 — 반증 지표가 없다는
// 사실 자체가 판정 불가의 이유이기 때문이다.
export function evidenceColumns(가설) {
  const 지지 = 가설?.지지 ?? [];
  const 반증 = 가설?.반증 ?? [];
  return {
    지지, 반증,
    지지비었음: 지지.length === 0,
    반증비었음: 반증.length === 0,
  };
}

// 규칙 3: 유의성사유("RSE 12.3%" · "RSE 미보유" · "RSE 미공표(*)")는 관측값이
// 아니라 표본오차다. 근거 표의 수치와 같은 자리·서식으로 그리면 사용자가 그
// 숫자를 관측값으로 읽는다. 렌더 쪽은 이 함수로 판정해 한계·주석 자리에,
// 시각적으로 구분되는 스타일로 둔다.
export function isSampleErrorText(s) {
  return typeof s === 'string' && /^RSE\b/.test(s.trim());
}

// Minor(리뷰 라운드 1): esc() 는 속성값을 이스케이프하지만 `javascript:` 스킴 자체를
// 막지는 못한다. 카탈로그(source_catalog.endpoint 등)가 오염돼도 클릭이 코드를
// 실행하지 않도록 http/https 화이트리스트만 링크로 그린다 — 그 외는 안전한
// 텍스트로만 보여준다.
export function safeHref(url) {
  return typeof url === 'string' && /^https?:\/\//i.test(url) ? url : null;
}
